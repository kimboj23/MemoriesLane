#!/usr/bin/env bash
# Demo deployment of the three apps on the VPS (run from deploy/demo, in an up-to-date checkout of main):
#   - the internal platform (hub) at https://$HUB_HOST   (sign-in by personal token)
#   - Hồ sơ Nhân quyền at https://$HSNQ_HOST
#   - the live community map: its existing backend (docker-compose.vps.yml) is connected to the hub
#
#   HUB_HOST=… HSNQ_HOST=… TUNNEL=<tunnel name> TILE_URL='https://{s}.basemaps…?key=…' ./setup.sh
#
# Idempotent: secrets and keys are generated once (gitignored files here); re-running rebuilds and re-checks.
# Options: BACKEND_REPO=<checkout running docker-compose.vps.yml> (default: this checkout), SKIP_TUNNEL=1 (no cloudflared changes), SKIP_BACKEND=1 (don't touch the community map's backend),
#          SEED=0 (no demo content), HUB_PORT / HSNQ_PORT (local ports, default 8700 / 3903).
#
# DEMO KEYS: the feed's root signing key is generated ON THIS SERVER, for the demo only. Production needs the
# offline root key held by the designated maintainer (docs/integration-design.md §13).
set -euo pipefail
cd "$(dirname "$0")"
HUB_HOST="${HUB_HOST:?set HUB_HOST, e.g. hub.example.org}"
HSNQ_HOST="${HSNQ_HOST:?set HSNQ_HOST, e.g. hosonhanquyen.example.org}"
HUB_PORT="${HUB_PORT:-8700}"; HSNQ_PORT="${HSNQ_PORT:-3903}"
export HUB_PORT HSNQ_PORT
COMPOSE="docker compose -f docker-compose.yml"
REPO="$(cd ../.. && pwd)"
# the checkout the community map's backend runs from (docker-compose.vps.yml + backend/.env); default: this one
BACKEND_REPO="${BACKEND_REPO:-$REPO}"
step() { printf '\n\033[1;36m== %s ==\033[0m\n' "$1"; }
rand() { python3 -c 'import secrets; print(secrets.token_hex(32))'; }

step "1. Secrets and keys (once)"
mkdir -p secrets && chmod 700 secrets
touch hsnq.env
if [ ! -f hub.env ]; then
  umask 077
  cat > hub.env <<EOF
# generated by setup.sh — gitignored
INTAKE_KEY_SECRET=$(rand)
ARTIFACT_URL_SECRET=$(rand)
FEED_SERVE_LOCAL=true
FEED_PUBLIC_URL=https://$HUB_HOST/feed
FEED_ONLINE_KEY=/secrets/feed-online.key
FEED_DELEGATION=/secrets/feed-delegation.json
TILE_URL=${TILE_URL:-https://{s}.basemaps.cartocdn.com/rastertiles/voyager/{z}/{x}/{y}{r}.png}
EOF
fi
$COMPOSE build
RUN="$COMPOSE run --rm --no-deps -T -v $PWD/secrets:/w hub-api"
# Key files belong to the container's user (mode 600) so the hub can read them; on Linux that is pwuser.
CUID="$($COMPOSE run --rm --no-deps -T hub-api id -u | tr -d '
')"
if [ "$(uname -s)" = "Linux" ] && [ "$(stat -c %u secrets)" != "$CUID" ]; then sudo chown "$CUID" secrets; fi
if [ ! -f root.pub ] || ! $COMPOSE run --rm --no-deps -T -v $PWD/secrets:/w hub-api test -f /w/feed-delegation.json; then
  $RUN python -m memlane_capture.feedkeys root-init --out /w/DEMO-feed-root.key > root.pub
  ONLINE=$($RUN python -m memlane_capture.feedkeys online-init --out /w/feed-online.key)
  $RUN python -m memlane_capture.feedkeys delegate --root /w/DEMO-feed-root.key --online-public "$ONLINE" --days 120 \
    --out /w/feed-delegation.json
fi
grep -q '^CONTACT_SECRET_KEY=' hub.env || $COMPOSE run --rm --no-deps -T hub-api python -m memlane_capture.admin contact-key-init \
  | grep '^CONTACT_SECRET_KEY=' >> hub.env

step "2. Start the hub"
$COMPOSE up -d hub-db hub-api hub-worker
for i in $(seq 1 60); do curl -fsS "http://127.0.0.1:$HUB_PORT/healthz" >/dev/null 2>&1 && break; sleep 2; done
curl -fsS "http://127.0.0.1:$HUB_PORT/healthz" >/dev/null || { echo "hub didn't start: $COMPOSE logs hub-api" >&2; exit 1; }
if [ ! -s ADMIN_TOKEN.txt ]; then
  $COMPOSE exec -T hub-api python -m memlane_capture.admin add-contributor "Demo admin" --email admin@demo.invalid --role admin >/dev/null
  $COMPOSE exec -T hub-api python -m memlane_capture.admin add-token admin@demo.invalid "demo setup" | tail -1 > ADMIN_TOKEN.txt
  chmod 600 ADMIN_TOKEN.txt
fi
TOKEN="$(cat ADMIN_TOKEN.txt)"
# the feed exists (and keys.json with it) once the worker has built it once
curl -fsS -X POST -H "Authorization: Bearer $TOKEN" "http://127.0.0.1:$HUB_PORT/v1/feed/rebuild" >/dev/null
for i in $(seq 1 30); do curl -fsS "http://127.0.0.1:$HUB_PORT/feed/keys.json" >/dev/null 2>&1 && break; sleep 2; done

step "3. Hồ sơ Nhân quyền: register and start"
eval "$(python3 hubctl.py "http://127.0.0.1:$HUB_PORT" "$TOKEN" source ho-so-nhan-quyen "Hồ sơ Nhân quyền" HSNQ "Hồ sơ Nhân quyền")"
umask 077
cat > hsnq.env <<EOF
# generated by setup.sh — gitignored (contains the source key)
HUB_URL=http://hub-api:8700
HUB_SOURCE=ho-so-nhan-quyen
HUB_INTAKE_KEY=$KEY
HUB_FEED_URL=http://hub-api:8700/feed
HUB_FEED_ROOT_KEY=$ROOT
FEED_COLLECTIONS=HSNQ
FEED_REFRESH_S=30
RATE_HMAC_SECRET=$(rand)
TILE_URL=$(sed -n 's/^TILE_URL=//p' hub.env)
EOF
$COMPOSE up -d hsnq
for i in $(seq 1 30); do curl -fsS "http://127.0.0.1:$HSNQ_PORT/api/status" >/dev/null 2>&1 && break; sleep 2; done
if [ "${SEED:-1}" = "1" ] && ! curl -fsS "http://127.0.0.1:$HSNQ_PORT/api/cases" | grep -q '"total":[1-9]'; then
  $COMPOSE run --rm -T -e HUB_URL=http://hub-api:8700 -e SITE_URL=http://hsnq:3903 -e HUB_ADMIN_TOKEN="$TOKEN" hsnq \
    node scripts/demo-seed.js content
fi

step "4. Community map: connect its backend to the hub"
if [ "${SKIP_BACKEND:-0}" != "1" ]; then
  eval "$(python3 hubctl.py "http://127.0.0.1:$HUB_PORT" "$TOKEN" source memorylane-map "Bản đồ cộng đồng" KYUC "Bản đồ ký ức")"
  BENV="$BACKEND_REPO/backend/.env"
  [ -f "$BENV" ] || { echo "$BENV not found" >&2; exit 1; }
  cp "$BENV" "$BENV.bak.$(date +%Y%m%d%H%M%S)"
  sed -i '/^HUB_\|^PUBLIC_SOURCE=/d' "$BENV"
  cat >> "$BENV" <<EOF
# --- MemoryLane hub (deploy/demo/setup.sh) ---
HUB_URL=https://$HUB_HOST
HUB_SOURCE=memorylane-map
HUB_INTAKE_KEY=$KEY
HUB_FEED_URL=https://$HUB_HOST/feed
HUB_FEED_ROOT_KEY=$ROOT
HUB_FEED_COLLECTIONS=KYUC
HUB_FEED_REFRESH_S=60
PUBLIC_SOURCE=feed
EOF
  (cd "$BACKEND_REPO" && docker compose -f docker-compose.vps.yml up -d --build backend)
  for i in $(seq 1 30); do curl -fsS http://127.0.0.1:3001/health >/dev/null 2>&1 && break; sleep 2; done
fi

step "5. Cloudflare tunnel: $HUB_HOST → :$HUB_PORT, $HSNQ_HOST → :$HSNQ_PORT"
if [ "${SKIP_TUNNEL:-0}" != "1" ]; then
  TUNNEL="${TUNNEL:?set TUNNEL (cloudflared tunnel list)}"
  CF="${CLOUDFLARED_CONFIG:-/etc/cloudflared/config.yml}"
  sudo cp "$CF" "$CF.bak.$(date +%Y%m%d%H%M%S)"
  for pair in "$HUB_HOST:$HUB_PORT" "$HSNQ_HOST:$HSNQ_PORT"; do
    host="${pair%%:*}"; port="${pair##*:}"
    if ! sudo grep -q "hostname: $host" "$CF"; then
      # insert above the catch-all "- service: http_status:404"
      sudo python3 - "$CF" "$host" "$port" <<'PY'
import sys
p, host, port = sys.argv[1:4]
s = open(p).read()
marker = "  - service: http_status:404"
assert marker in s, "catch-all rule not found in " + p
s = s.replace(marker, f"  - hostname: {host}\n    service: http://localhost:{port}\n{marker}", 1)
open(p, "w").write(s)
PY
    fi
    cloudflared tunnel route dns "$TUNNEL" "$host" || true
  done
  sudo cloudflared --config "$CF" tunnel ingress validate
  sudo systemctl restart cloudflared
  sleep 5
fi

step "6. Demo content on the community map, and checks"
if [ "${SEED:-1}" = "1" ] && [ "${SKIP_BACKEND:-0}" != "1" ]; then
  python3 hubctl.py "http://127.0.0.1:$HUB_PORT" "$TOKEN" seed-map http://127.0.0.1:3001 KYUC || echo "(map demo content: skipped)"
fi
curl -fsS "http://127.0.0.1:$HSNQ_PORT/api/status"; echo
if [ "${SKIP_TUNNEL:-0}" != "1" ]; then
  for u in "https://$HUB_HOST/healthz" "https://$HUB_HOST/feed/index.json" "https://$HSNQ_HOST/api/status"; do
    printf '%-60s %s\n' "$u" "$(curl -s -o /dev/null -w '%{http_code}' "$u")"
  done
fi
cat <<EOF

Done.
  Internal platform: https://$HUB_HOST/app/   (admin token: deploy/demo/ADMIN_TOKEN.txt — store it, then delete the file)
  Hồ sơ Nhân quyền:  https://$HSNQ_HOST/
  Community map:     the live site (its backend now reads the hub's feed, PUBLIC_SOURCE=feed)
  Feed root public key (DEMO): $(cat root.pub 2>/dev/null)
EOF
